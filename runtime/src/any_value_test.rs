#[test]
fn render_float_matches_elixir_inspect() {
    use crate::any_value::debug::render_float;
    let mismatches: Vec<String> = ELIXIR_FLOAT_RENDERINGS
        .iter()
        .filter_map(|(bits, inspected, _)| {
            let rendered = render_float(f64::from_bits(*bits));
            (rendered != *inspected).then(|| format!("{bits:#018x}: fz {rendered} != elixir {inspected}"))
        })
        .collect();
    assert!(
        mismatches.is_empty(),
        "`dbg` renders floats through this, and the oracle twins print with `inspect`:\n{}",
        mismatches.join("\n"),
    );
}

#[test]
fn float_to_string_matches_elixir_float_to_string() {
    use crate::any_value::debug::float_to_string;
    let mismatches: Vec<String> = ELIXIR_FLOAT_RENDERINGS
        .iter()
        .filter_map(|(bits, _, to_string)| {
            let rendered = float_to_string(f64::from_bits(*bits));
            (rendered != *to_string).then(|| format!("{bits:#018x}: fz {rendered} != elixir {to_string}"))
        })
        .collect();
    assert!(
        mismatches.is_empty(),
        "`String.Chars` and interpolation render floats through this:\n{}",
        mismatches.join("\n"),
    );
}

/// The two differ, and only here: a WHOLE float in `[1.0, 1.0e16)` inspects in
/// full and to_strings in whichever notation is shorter. Pinned separately
/// because a future "simplification" that collapses them into one function
/// would still pass the tables above for every other value.
#[test]
fn inspect_and_to_string_differ_only_on_whole_floats_below_1e16() {
    use crate::any_value::debug::{float_to_string, render_float};
    assert_eq!(render_float(1.0e15), "1000000000000000.0");
    assert_eq!(float_to_string(1.0e15), "1.0e15");
    assert_eq!(render_float(1.5e15), "1500000000000000.0");
    assert_eq!(float_to_string(1.5e15), "1.5e15");
    // Not whole: the special case cannot apply, so both take the same form.
    assert_eq!(render_float(123.25), "123.25");
    assert_eq!(float_to_string(123.25), "123.25");
    // At and above the boundary they agree again.
    assert_eq!(render_float(1.0e16), "1.0e16");
    assert_eq!(float_to_string(1.0e16), "1.0e16");
    // Below 1.0 the special case cannot apply.
    assert_eq!(render_float(0.5), "0.5");
    assert_eq!(float_to_string(0.5), "0.5");
}

/// The notation rule is length-based below `1.0e16`, not a magnitude
/// threshold. These two floats share an exponent and render differently, which
/// no threshold can produce -- so a rewrite to `if exponent > N` fails here
/// rather than in an oracle diff months later.
#[test]
fn notation_is_chosen_by_length_not_magnitude() {
    use crate::any_value::debug::float_to_string;
    assert_eq!(float_to_string(1.0e14), "1.0e14");
    assert_eq!(float_to_string(123456789012345.0), "123456789012345.0");
    // A tie goes to positional: `0.0001` and `1.0e-4` are both six characters.
    assert_eq!(float_to_string(0.0001), "0.0001");
    assert_eq!(float_to_string(1.0e-5), "1.0e-5");
}

#[test]
fn a_node_built_by_normal_form_that_says_what_a_node_says_is_that_node() {
    let (mut t, sys) = system();
    let minimal = t.minimise(sys);
    let next = {
        let normalised = t.normalise_round(&minimal);
        t.quotient(normalised)
    };
    assert!(next == minimal, "a round of the minimal system changes it");
}
